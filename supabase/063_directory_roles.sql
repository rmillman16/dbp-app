-- 063 · Project directory roles: a fuller list, including every trade, that anyone can add to (23 Nov)
-- Richard: the directory's roles needed to be more exhaustive, with trades, and to add a new one from the dropdown.
-- - directory_roles holds the list (seeded below: client side, design team, management / cost / statutory, trades).
--   Anyone signed in can add a role from the dropdown in the project directory, the RFI / submittal pickers and
--   the O&M tab; the list is shared by everyone. Existing roles on jobs are untouched
-- - roles are also how RFI and submittal templates find people ("Joinery subcontractor")
-- Safe to run more than once. No existing data is lost (run after 062).
-- =====================================================================
create table if not exists directory_roles (
  name        text primary key,
  created_by  uuid references profiles(id) on delete set null default auth.uid(),
  created_at  timestamptz not null default now()
);
alter table directory_roles enable row level security;
grant select, insert, delete on directory_roles to authenticated;
drop policy if exists "signed-in users" on directory_roles;
create policy "signed-in users" on directory_roles for select to authenticated using (true);
drop policy if exists "anyone adds a role" on directory_roles;
create policy "anyone adds a role" on directory_roles for insert to authenticated with check (true);
drop policy if exists "admins remove a role" on directory_roles;
create policy "admins remove a role" on directory_roles for delete to authenticated using (public.is_admin());

